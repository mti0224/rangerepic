import type { Role } from './rangerClass'

export interface RoleTrait {
  label: string
  text: string
  /** เลือกเป้าได้ทุกตัว ไม่ต้องตีแถวหน้าก่อน (มีผลกับตีปกติ) */
  strikeAnyone?: boolean
  /** ดาเมจที่ได้รับ × */
  damageTaken?: number
  /** บอทฝ่ายตรงข้ามให้คะแนนการตีตัวนี้ × (ดึงความสนใจ) */
  threat?: number
  /** ฟื้นเลือดเท่ากับดาเมจที่ทำได้ × */
  lifesteal?: number
  /** ดาเมจตีปกติ × */
  normalDamage?: number
  /** ดาเมจสกิลโจมตี × */
  skillDamage?: number
  /** ดาเมจเมื่อเป้าเลือดต่ำกว่าครึ่งหลอด × */
  executeDamage?: number
  /** ยิ่งเลือดตัวเองน้อยยิ่งแรง: ดาเมจ × (1 + ค่านี้ × สัดส่วนเลือดที่หายไป) */
  desperation?: number
  /** ตีเป้าที่เลือดเกินครึ่ง: ดาเมจ × (1 + ค่านี้) */
  bigTargetDamage?: number
  /** ฮีล/โล่ที่ตัวนี้ให้ × */
  supportPower?: number
  /** พลังงานเริ่มเกมของทีม + (ทีมหนึ่งได้อย่างมาก +1 แม้มีหลายตัว) */
  energyBonus?: number
}

